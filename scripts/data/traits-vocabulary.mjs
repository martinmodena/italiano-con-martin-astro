for (const t of everyTrait) {
  if (t.slug === 'selvaggio') {
    t.matches = animalVocabulary.map((a) => a.slug).filter((slug) => !clearlyDomestic.includes(slug));
    t.never = clearlyDomestic.filter((slug) => !t.matches.includes(slug));
  }
}
